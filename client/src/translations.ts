export function t(locale: Locale, key: string, params?: Record<string, string | number>): string {
  let text = translations[locale][key as keyof typeof translations['en']] || key;
  
  if (params) {
    Object.entries(params).forEach(([param, value]) => {
      text = text.replace(`{${param}}`, String(value));
    });
  }
  
  return text;
}

// Helper function to translate mood and energy values
export function translateValue(locale: Locale, value: string): string {
  // Convert value to camelCase key format
  const key = 'mood' + value.split('-').map(word => 
    word.charAt(0).toUpperCase() + word.slice(1)
  ).join('');
  
  // Try mood translation
  let translated = translations[locale][key as keyof typeof translations['en']];
  if (translated) return translated;
  
  // Try energy translation
  const energyKey = 'energy' + value.split('-').map(word => 
    word.charAt(0).toUpperCase() + word.slice(1)
  ).join('');
  translated = translations[locale][energyKey as keyof typeof translations['en']];
  if (translated) return translated;
  
  // Return original if no translation found
  return value;
}

// Helper function to translate delivery method
export function translateDeliveryMethod(locale: Locale, method: string): string {
  const methodMap: Record<string, keyof typeof translations['en']> = {
    'vaginal': 'deliveryVaginal',
    'c-section': 'deliveryCSection',
    'assisted': 'deliveryAssisted'
  };
  
  const key = methodMap[method];
  return key ? translations[locale][key] : method;
}
